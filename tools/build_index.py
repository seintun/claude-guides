"""Build the files an agent without a clone reads: guide-index.json, sections/<id>.md and routes/.

An agent that only has the repository link can fetch these over plain HTTP. It reads
guide-index.json (or ENTRY.md) to route, then fetches only the sections a route names, never
the whole playbook. routes/row-<n>.md and routes/phase-<n>.md bundle one route's sections and
templates, so ENTRY.md plus one fetch is enough. tools/section.py serves the same text to an agent with a clone.

Usage: python3 -I tools/build_index.py              rebuild guide-index.json and sections/
       python3 -I tools/build_index.py --out DIR    write them under DIR instead (the staleness test uses this)
Generated files: never edit them by hand. tests/test_generated.py fails while they are stale.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))   # python3 -I leaves the script's folder off sys.path
import section  # noqa: E402

HEADER = "<!-- Generated by tools/build_index.py from {src}. Do not edit; rebuild. -->\n"
HOW_TO = [
    "Route first: match the request to one row of 'router' (or 'phases' when it is a stage of work).",
    "Fetch the row's 'bundle' (its sections and templates in one file), or only its 'read' ids at sections[id].path. Never fetch the whole playbook.",
    "Open the row's runbook only if you need its steps and checklist.",
    "Paths are relative to the repository root. Without a clone, prefix them with "
    "https://raw.githubusercontent.com/<owner>/<repo>/<branch>/ taken from the link you were given (main unless it names a branch). "
    "Fetch raw text; a summarising fetch tool can shorten a file.",
    "Rows marked thin have no full recipe; say so instead of filling the gap from memory.",
]


def file_of(key):
    """sections/ file name for an id; ':' is not portable in file names, so cs:3 becomes cs-3."""
    return f"sections/{key.replace(':', '-')}.md"


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def table(text, first_header):
    """Rows of the Markdown table whose header row starts with first_header."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("|") and cells(line)[0] == first_header:
            rows = []
            for row in lines[i + 2:]:
                if not row.startswith("|"):
                    break
                rows.append(cells(row))
            return rows
    raise SystemExit(f"ENTRY.md has no table starting with '| {first_header} |'")


def ids(cell):
    return [tok for code in re.findall(r"`([^`]+)`", cell) for tok in code.split()]


def links(cell):
    return [p for p in re.findall(r"\]\(([^)#]+)\)", cell)]


def letters(cell):
    return re.findall(r"\b([A-M])\b", cell)


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    fields = {}
    for line in (m.group(1) if m else "").splitlines():
        k, _, v = line.partition(":")
        if v:
            fields[k.strip()] = v.strip()
    return fields


def build():
    """Return {relative path: text} for every generated file."""
    out = {}
    entries = []
    for src, cheatsheet in ((section.PLAYBOOK, False), (section.CHEATSHEET, True)):
        lines, found = section.index(src, cheatsheet=cheatsheet)
        rel = src.relative_to(ROOT).as_posix()
        for key, (title, i, end) in found.items():
            body = "\n".join(lines[i:end]).rstrip() + "\n"
            # sections/ sits at the same depth as playbook/, so ../ links still resolve; same-file anchors don't.
            body = body.replace("](#", f"](../{rel}#")
            out[file_of(key)] = HEADER.format(src=rel) + body
            entries.append({"id": key, "title": title, "lines": end - i, "chars": len(body), "path": file_of(key), "source": rel})

    entry = (ROOT / "ENTRY.md").read_text(encoding="utf-8")
    router = []
    for c in table(entry, "#"):
        n, scenario, read, runbook, template, output = c[:6]
        router.append({
            "row": int(n), "scenario": scenario, "thin": "(thin" in scenario,
            "read": ids(read), "runbooks": links(runbook), "templates": letters(template),
            "template_note": template, "output": output,
        })
    phases = [{"phase": p, "read": ids(r), "runbooks": links(rb), "templates": letters(t)}
              for p, r, rb, t in (c[:4] for c in table(entry, "Phase"))]

    # One file per route: its section ids, then any template letters not already among them.
    for name, route, label in ([(f"row-{r['row']}", r, f"Router row {r['row']}: {r['scenario']}") for r in router] +
                               [(f"phase-{p['phase'].split()[0]}", p, f"Phase {p['phase']}") for p in phases]):
        keys = list(dict.fromkeys(route["read"] + route["templates"]))
        parts = [f"<!-- id: {k} -->\n" + out[file_of(k)].split("\n", 1)[1] for k in keys]
        route["bundle"] = f"routes/{name}.md"
        out[route["bundle"]] = (HEADER.format(src="ENTRY.md and the playbook") + f"# {label}\n\n"
                                f"Sections and templates this route names, in order: {', '.join(keys)}. "
                                f"Runbook, if you need its steps: {', '.join(route['runbooks']) or 'none'}.\n\n"
                                + "\n".join(parts))

    runbooks = []
    for p in sorted((ROOT / "wiki").glob("*.md")):
        if p.name == "README.md":
            continue
        title = next((l[2:].strip() for l in p.read_text(encoding="utf-8").splitlines() if l.startswith("# ")), p.stem)
        runbooks.append({"name": p.stem, "title": title, "path": p.relative_to(ROOT).as_posix()})

    skills = []
    for p in sorted((ROOT / "skills").glob("*/SKILL.md")):
        fm = frontmatter(p)
        skills.append({"name": fm.get("name", p.parent.name), "description": fm.get("description", ""),
                       "path": p.relative_to(ROOT).as_posix(),
                       "install": f"npx skills add <owner>/<repo> --skill {p.parent.name}"})

    index = {
        "about": "Machine-readable map of the claude-guides playbook. Generated by tools/build_index.py; do not edit.",
        "how_to_use": HOW_TO,
        "entry": "ENTRY.md",
        "router": router,
        "phases": phases,
        "sections": entries,
        "runbooks": runbooks,
        "skills": skills,
    }
    out["guide-index.json"] = json.dumps(index, indent=1, ensure_ascii=False) + "\n"

    listing = "\n".join(f"| [`{e['id']}`]({pathlib.Path(e['path']).name}) | {e['title']} | {e['lines']} |" for e in entries)
    out["sections/README.md"] = (HEADER.format(src="the playbook and cheat sheet") +
        "# sections\n\nOne file per playbook section, law, template and cheat-sheet section, so an agent without a clone "
        "can fetch exactly what a route in [ENTRY.md](../ENTRY.md) names. The same text `tools/section.py` prints, with same-file anchors pointed at the playbook. "
        "File names use the section id; `cs:3` becomes `cs-3.md`.\n\n"
        "| Id | Title | Lines |\n|---|---|---|\n" + listing + "\n")
    out["routes/README.md"] = (HEADER.format(src="ENTRY.md") +
        "# routes\n\nOne file per [ENTRY.md](../ENTRY.md) router row (`row-<n>.md`) and phase (`phase-<n>.md`): "
        "the row's sections and templates in one file, so an agent without a clone needs ENTRY.md plus one fetch. "
        "The single files are in [sections/](../sections/README.md).\n")
    return out


def main(argv):
    dest = ROOT
    if argv[:1] == ["--out"] and len(argv) == 2:
        dest = pathlib.Path(argv[1])
    elif argv:
        print(__doc__.strip())
        return 1
    files = build()
    for folder in ("sections", "routes"):
        (dest / folder).mkdir(parents=True, exist_ok=True)
        for old in (dest / folder).glob("*.md"):
            if f"{folder}/{old.name}" not in files:
                old.unlink()
    for rel, text in files.items():
        (dest / rel).write_text(text, encoding="utf-8")
    print(f"wrote guide-index.json, sections/ and routes/ ({len(files) - 1} files) under {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
