"""Copy a tagged version of the guide into archive/<version>/ as a read-only snapshot.

Usage (from the repository root):
    python3 -I tools/archive_snapshot.py --tag guide-v0.6 --version 0.6 --date 2026-10-27

What it does:
- Reads each file from the git tag, not the working tree, so the snapshot is exactly the tagged text.
- Rewrites every relative Markdown link to a GitHub permalink at the tag, so links in the archive
  never break when the live files move on, and tools/check_links.py needs no exemption.
- Adds a banner at the top of each file: the version, the date, and a link to the current file.
- Copies the teaching page source to site/history/orchestrating-claude-v<page>.html unchanged,
  following the existing pattern for v11.

The archive is history. Never edit a snapshot by hand; run this script again instead.
"""
import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_URL = "https://github.com/seintun/claude-guides"
MD_FILES = ["playbook/agent-harness-playbook.md", "playbook/claude-cheat-sheet.md",
            "ENTRY.md", "orchestration-index.md"]
HTML_FILES = ["docs/orchestrating-claude-compendium.html"]
PAGE_SOURCE = "site/orchestrating-claude.html"


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def tagged_files(tag):
    wiki = [p for p in git("ls-tree", "--name-only", tag, "wiki/").split() if p.endswith(".md")]
    return MD_FILES + wiki


def permalink(tag, src_rel, target):
    file_part, hashmark, anchor = target.partition("#")
    resolved = os.path.normpath(os.path.join(os.path.dirname(src_rel), file_part)).replace(os.sep, "/")
    kind = "tree" if resolved.endswith("/") or "." not in os.path.basename(resolved) else "blob"
    return f"{REPO_URL}/{kind}/{tag}/{resolved}" + (f"#{anchor}" if hashmark else "")


def rewrite_links(text, tag, src_rel):
    out, fence = [], False
    for line in text.split("\n"):
        if line.strip().startswith("```"):
            fence = not fence
            out.append(line)
            continue
        if fence:
            out.append(line)
            continue
        # Leave inline code alone: split on backticks and only touch the even (outside-code) parts.
        parts = line.split("`")
        for i in range(0, len(parts), 2):
            parts[i] = re.sub(
                r"\]\(([^)\s]+)\)",
                lambda m: m.group(0) if re.match(r"(https?|mailto):|#", m.group(1))
                else f"]({permalink(tag, src_rel, m.group(1))})",
                parts[i])
        out.append("`".join(parts))
    return "\n".join(out)


def banner_md(version, date, tag, src_rel, dest_rel):
    here = os.path.dirname(os.path.join(ROOT, dest_rel))
    current = os.path.relpath(os.path.join(ROOT, src_rel), here)
    index = os.path.relpath(os.path.join(ROOT, "archive", "README.md"), here)
    return (f"> **Archived snapshot, version {version} ({date}).** Copied from tag `{tag}`. "
            f"The current version is [{src_rel}]({current}). Links below point to the tagged version. "
            f"Do not edit this file; see [the archive index]({index}) for what replaced it.\n\n")


def banner_html(version, date, tag):
    return (f'<!-- Archived snapshot, version {version} ({date}), copied from tag {tag}. Do not edit. -->\n'
            f'<div style="padding:8px 16px;background:#fff4d6;color:#3a2a00;font:14px/1.4 system-ui,sans-serif">'
            f'Archived snapshot, version {version} ({date}). The current version is published at '
            f'<a href="https://seintun.github.io/claude-guides/">seintun.github.io/claude-guides</a>.</div>\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--tag", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--date", required=True)
    ap.add_argument("--page", help="teaching page version, to copy the page source to site/history/")
    a = ap.parse_args()
    dest_root = f"archive/v{a.version}"
    written = []
    for rel in tagged_files(a.tag):
        dest_rel = f"{dest_root}/{rel}"
        body = rewrite_links(git("show", f"{a.tag}:{rel}"), a.tag, rel)
        os.makedirs(os.path.join(ROOT, os.path.dirname(dest_rel)), exist_ok=True)
        with open(os.path.join(ROOT, dest_rel), "w", encoding="utf-8") as f:
            f.write(banner_md(a.version, a.date, a.tag, rel, dest_rel) + body)
        written.append(dest_rel)
    for rel in HTML_FILES:
        dest_rel = f"{dest_root}/{rel}"
        body = git("show", f"{a.tag}:{rel}")
        body = re.sub(r"(<body[^>]*>)", lambda m: m.group(1) + "\n" + banner_html(a.version, a.date, a.tag), body, count=1)
        os.makedirs(os.path.join(ROOT, os.path.dirname(dest_rel)), exist_ok=True)
        with open(os.path.join(ROOT, dest_rel), "w", encoding="utf-8") as f:
            f.write(body)
        written.append(dest_rel)
    if a.page:
        dest_rel = f"site/history/orchestrating-claude-v{a.page}.html"
        with open(os.path.join(ROOT, dest_rel), "w", encoding="utf-8") as f:
            f.write(git("show", f"{a.tag}:{PAGE_SOURCE}"))
        written.append(dest_rel)
    for w in written:
        print("wrote", w)
    return 0


if __name__ == "__main__":
    sys.exit(main())
