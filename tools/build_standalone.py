"""Wrap the artifact page in a full HTML document, so it also works outside claude.ai.

The artifact source (site/orchestrating-claude.html) has no doctype, head or body:
the claude.ai viewer adds them. Opened on its own, a browser renders it in quirks
mode, and dev servers such as VS Code Live Server inject their reload script before
every </svg> because there is no </body>. Both break the figures. This script adds
the same skeleton and base styles the viewer adds.

Usage: python3 -I tools/build_standalone.py [page.html] [out.html]
Defaults: site/orchestrating-claude.html -> site/index.html
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
page = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "site" / "orchestrating-claude.html"
out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "site" / "index.html"

body = page.read_text(encoding="utf-8")

# Move the leading <title>, <meta> and <link> tags into <head>.
lead = re.match(r"(?:\s*(?:<title>.*?</title>|<meta\b[^>]*>|<link\b[^>]*>))+", body, re.S)
head_tags = lead.group(0).strip() if lead else ""
body = body[lead.end():].lstrip("\n") if lead else body

# What the claude.ai artifact viewer adds around every page.
VIEWER_BASE = (
    ":root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);"
    "padding-bottom:env(safe-area-inset-bottom,0px)}"
    "body{margin:0;font:14px/1.5 system-ui,-apple-system,'Segoe UI',Roboto,sans-serif}"
    "img{max-width:100%}"
    "[hidden]{display:none!important}"
)

doc = (
    "<!doctype html>\n"
    "<!-- Generated by tools/build_standalone.py from "
    f"{page.resolve().relative_to(ROOT) if page.resolve().is_relative_to(ROOT) else page.name}."
    " Do not edit by hand. -->\n"
    '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
    f"<style>{VIEWER_BASE}</style>\n{head_tags}\n</head>\n<body>\n{body.rstrip()}\n</body>\n</html>\n"
)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(doc, encoding="utf-8")
print(f"wrote {out.relative_to(ROOT) if out.resolve().is_relative_to(ROOT) else out}: {len(doc.encode()) // 1024} KB")
