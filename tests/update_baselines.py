"""Write tests/baselines/playbook.json from the current playbook, and define how the playbook is measured.

Run (from the repository root): python3 -I tests/update_baselines.py [--allow-shrink]

The playbook is the repository's guiding star. tests/test_playbook.py compares it with this
baseline so a careless or catastrophic edit fails loudly. Run this script only when a change to
the playbook is intended (a section added, a source dropped, a claim re-graded on purpose), then
commit the new baseline with the change. The file has no date or other noise, so a second run
on the same playbook writes the same bytes and a diff shows only what really changed.

What it records:
  version        the "Version X.Y" line within the first 10 lines
  line_count     the number of lines in the file
  headings       every Markdown heading outside code fences, in order, as the heading line
                 itself ("## 9. Verification stack": the number of # is the level)
  source_urls    every http(s) URL in section 20, sorted, trailing . , ; : removed
  evidence_tags  how many times each grade P, S, R, D is used
  sections       for every playbook heading, the words in its own body (the lines under it up to
                 the next heading of any level, code fences included) and the [P] [S] [R] [D]
                 tags in that body
  cheatsheet_sections  the same record for every heading of playbook/claude-cheat-sheet.md

An evidence tag is "[" followed by one grade letter, then "]", ":", ";", "," or a space. The
playbook writes tags as [P], [S: talk summary], [P, vendor] and [P; the caution is D]; each
counts once, for its first letter. Link text such as [D. Plan file] in the contents does not
count, because a "." follows the letter. Tags inside code fences count too: the rule is simple
on purpose, and both the baseline and the tests use this one definition.

The script refuses to write a baseline that removes a heading (playbook or cheat sheet) or a source
URL, or that takes any section below 70% of its old words, so one careless run cannot launder a
hollowed-out guide into the new normal. Pass --allow-shrink when the loss is intended; it prints
what shrank. It also prints any section whose [P] count rose while its [D], [S] or [R] count fell
by as much: a grade moved up without a new source. Confirm each one has a primary source behind it.

tests/test_playbook.py, tests/test_docs.py and tests/test_guardrails.py import the helpers below,
so the way a heading, a slug, a source URL, a tag, a section's size or a promotion is read is
defined in one place.
"""
import argparse
import json
import pathlib
import re
import sys
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[1]
PLAYBOOK = ROOT / "playbook" / "agent-harness-playbook.md"
CHEATSHEET = ROOT / "playbook" / "claude-cheat-sheet.md"
BASELINE = ROOT / "tests" / "baselines" / "playbook.json"

GRADES = ("P", "S", "R", "D")
TAG = re.compile(r"\[([PSRD])(?=[\]:;,\s])")
URL = re.compile(r"https?://[^\s)\]>`'\"]+")
VERSION = re.compile(r"^Version (\d+\.\d+)\b")

ABOUT = (
    "Generated by tests/update_baselines.py from playbook/agent-harness-playbook.md. Do not edit by hand. "
    "headings: every heading outside code fences, in order, as the heading line. "
    "source_urls: every http(s) URL in section 20. evidence_tags: uses of [P] [S] [R] [D] "
    "(see the script's docstring for the exact rule). "
    "sections and cheatsheet_sections: per heading, the words in its own body and its [P] [S] [R] [D] counts."
)
KEEP_PERCENT = 70          # a section may lose words, but not more than 30% of its baseline
SECTION_KEYS = ("sections", "cheatsheet_sections")


def headings(text):
    """(line index, level, title) for each Markdown heading outside code fences."""
    out, fence = [], False
    for i, line in enumerate(text.splitlines()):
        if line.lstrip().startswith("```"):
            fence = not fence
            continue
        m = None if fence else re.match(r"(#{1,6}) (.*)", line)
        if m:
            out.append((i, len(m.group(1)), m.group(2).strip()))
    return out


def slugify(title):
    """GitHub's anchor for a heading title (the same rule tools/check_links.py uses)."""
    text = re.sub(r"`([^`]*)`", r"\1", title)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return re.sub(r"[^\w\- ]", "", text.strip().lower(), flags=re.UNICODE).replace(" ", "-")


def slug_set(text):
    """Every anchor a file's headings answer to, with GitHub's -1, -2 suffix for repeats."""
    seen, out = {}, set()
    for _, _, title in headings(text):
        s = slugify(title)
        n = seen.get(s, 0)
        out.add(s if n == 0 else f"{s}-{n}")
        seen[s] = n + 1
    return out


def sources_section(text):
    """The text of section 20 (from its heading to the next level-1 or level-2 heading, or the end)."""
    lines = text.splitlines()
    heads = headings(text)
    for n, (i, level, title) in enumerate(heads):
        if level == 2 and re.match(r"20\. ", title):
            end = len(lines)
            for j, lvl, _ in heads[n + 1:]:
                if lvl <= 2:
                    end = j
                    break
            return "\n".join(lines[i:end])
    return ""


def source_urls(text):
    """The set of URLs in section 20."""
    return {u.rstrip(".,;:") for u in URL.findall(sources_section(text))}


def version(text):
    """The "X.Y" of the Version line in the first 10 lines, or None."""
    for line in text.splitlines()[:10]:
        m = VERSION.match(line)
        if m:
            return m.group(1)
    return None


def evidence_tags(text):
    """How many times each grade is used."""
    counts = {g: 0 for g in GRADES}
    for m in TAG.finditer(text):
        counts[m.group(1)] += 1
    return counts


def section_stats(text):
    """{heading line: {"words", "P", "S", "R", "D"}} for the body each heading owns.

    A heading's own body is the text under it up to the next heading of any level (code fences
    included), so a parent does not hide a hollowed subsection. A repeated heading line gets
    " (2)", " (3)" ... added to its key.
    """
    lines = text.splitlines()
    heads = headings(text)
    out, seen = {}, Counter()
    for n, (i, level, title) in enumerate(heads):
        end = heads[n + 1][0] if n + 1 < len(heads) else len(lines)
        body = "\n".join(lines[i + 1:end])
        key = "#" * level + " " + title
        seen[key] += 1
        if seen[key] > 1:
            key += f" ({seen[key]})"
        out[key] = {"words": len(body.split()), **evidence_tags(body)}
    return out


def word_floor(was):
    """The fewest words a section may keep: KEEP_PERCENT of its baseline, rounded down."""
    return was * KEEP_PERCENT // 100


# A few graded claims may be removed in an ordinary edit; more than this needs --allow-shrink.
TAG_SLACK = 3


def promotions(old_sections, new_sections):
    """Messages for sections whose [P] count rose while [D], [S] or [R] fell by the same or more.

    That pattern is a claim re-graded upward. A real promotion needs a new primary source behind it.
    """
    out = []
    for key, was in old_sections.items():
        now = new_sections.get(key)
        if not now or now["P"] <= was["P"]:
            continue
        rose = now["P"] - was["P"]
        for g in ("D", "S", "R"):
            if was[g] - now[g] >= rose:
                out.append(f"{key}: [P] {was['P']} -> {now['P']} while [{g}] {was[g]} -> {now[g]}")
                break
    return out


def measure(text):
    """Everything the baseline records for a playbook given as text (the cheat sheet is measured separately)."""
    return {
        "version": version(text),
        "line_count": len(text.splitlines()),
        "headings": ["#" * level + " " + title for _, level, title in headings(text)],
        "source_urls": sorted(source_urls(text)),
        "evidence_tags": evidence_tags(text),
        "sections": section_stats(text),
    }


def measure_all():
    """measure() for the playbook plus the cheat sheet's per-heading record."""
    now = measure(PLAYBOOK.read_text(encoding="utf-8"))
    now["cheatsheet_sections"] = section_stats(CHEATSHEET.read_text(encoding="utf-8"))
    return now


def shrinkage(old, now):
    """Messages for what a new measurement removes or shrinks against an older baseline."""
    out = []
    gone = list((Counter(old.get("headings", [])) - Counter(now["headings"])).elements())
    out += [f"heading removed or renamed: {h}" for h in gone]
    out += [f"cheat-sheet heading removed or renamed: {h}"
            for h in old.get("cheatsheet_sections", {}) if h not in now["cheatsheet_sections"]]
    out += [f"source URL removed from section 20: {u}" for u in sorted(set(old.get("source_urls", [])) - set(now["source_urls"]))]
    for field, label in (("sections", "playbook"), ("cheatsheet_sections", "cheat sheet")):
        for key, was in old.get(field, {}).items():
            cur = now[field].get(key)
            if cur and cur["words"] < word_floor(was["words"]):
                out.append(f"{label} section below {KEEP_PERCENT}% of its words: {key} "
                           f"({was['words']} -> {cur['words']}, floor {word_floor(was['words'])})")
    # Re-grading or stripping grades is a loss too: regenerating the baseline must not launder it.
    out += [f"grade promoted without a new source: {m}" for m in promotions(old.get("sections", {}), now["sections"])]
    for g, was in old.get("evidence_tags", {}).items():
        cur = now["evidence_tags"].get(g, 0)
        if cur < was - TAG_SLACK:
            out.append(f"[{g}] evidence tags fell from {was} to {cur}, more than {TAG_SLACK}")
    return out


def render(data):
    """JSON text for the baseline: one line per section, so a diff shows exactly which section moved."""
    parts = []
    for key, value in data.items():
        if key in SECTION_KEYS:
            rows = [f"    {json.dumps(h, ensure_ascii=False)}: {json.dumps(stats)}" for h, stats in value.items()]
            parts.append(f"  {json.dumps(key)}: {{\n" + ",\n".join(rows) + "\n  }")
        else:
            parts.append(f"  {json.dumps(key)}: " + json.dumps(value, indent=2, ensure_ascii=False).replace("\n", "\n  "))
    return "{\n" + ",\n".join(parts) + "\n}\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write tests/baselines/playbook.json from the current playbook.")
    ap.add_argument("--allow-shrink", action="store_true",
                    help="write the baseline even if it removes headings or source URLs or shrinks a section below "
                         f"{KEEP_PERCENT}%% of its words (the loss is printed)")
    args = ap.parse_args(argv)
    now = measure_all()
    if now["version"] is None or not now["source_urls"]:
        print("refusing to write a baseline: the playbook has no Version line or no section 20 URLs. "
              "Fix the playbook first.", file=sys.stderr)
        return 1
    old = json.loads(BASELINE.read_text(encoding="utf-8")) if BASELINE.exists() else {}
    lost = shrinkage(old, now)
    if lost and not args.allow_shrink:
        print(f"refusing to write a baseline: {len(lost)} heading(s), source URL(s) or section(s) were lost or shrank:", file=sys.stderr)
        for line in lost:
            print(f"  {line}", file=sys.stderr)
        print("Restore them. If the loss is intended, run python3 -I tests/update_baselines.py --allow-shrink "
              "and commit the baseline with the change.", file=sys.stderr)
        return 1
    BASELINE.parent.mkdir(parents=True, exist_ok=True)
    BASELINE.write_text(render({"_about": ABOUT, **now}), encoding="utf-8")
    tags = " ".join(f"{g}={n}" for g, n in now["evidence_tags"].items())
    print(f"wrote {BASELINE.relative_to(ROOT)}")
    print(f"  version {now['version']}, {now['line_count']} lines")
    print(f"  {len(now['headings'])} headings, {len(now['source_urls'])} source URLs")
    print(f"  {len(now['sections'])} playbook sections and {len(now['cheatsheet_sections'])} cheat-sheet sections recorded")
    print(f"  evidence tags: {tags}")
    if lost:
        print(f"allowed by --allow-shrink: {len(lost)} loss(es)")
        for line in lost:
            print(f"  {line}")
    promoted = promotions(old.get("sections", {}), now["sections"])
    if promoted:
        print(f"check these {len(promoted)} section(s): a grade moved up without a visible source. "
              "Each [P] needs a primary source in section 20:")
        for line in promoted:
            print(f"  {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
